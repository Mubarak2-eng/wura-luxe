export const getProductBySlug = (slug) => products.find((p) => p.slug === slug)
export const getProductById = (id) => products.find((p) => p.id === id)
export const getFeaturedProducts = () => products.filter((p) => p.featured)
export const getBestSellers = () => products.filter((p) => p.bestSeller)
export const getNewArrivals = () => products.filter((p) => p.isNew)
export const getProductsByCategory = (category) =>
  products.filter((p) => p.category === category)
export const getProductsByGender = (gender) =>
  products.filter((p) => p.gender.toLowerCase() === gender.toLowerCase() || p.gender === 'Unisex')
export const getProductsByScent = (scent) =>
  products.filter((p) => p.scentProfile.toLowerCase().includes(scent.toLowerCase()))
